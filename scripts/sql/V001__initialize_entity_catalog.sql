-- Điều kiện chạy: PostgreSQL 16 trở lên, ứng dụng đã dừng, TẤT CẢ bảng nghiệp vụ trong schema public đều không có dữ liệu.

-- Giữ lại các cột và bảng cũ; không thực hiện INSERT/UPDATE/DELETE hoặc thêm dữ liệu nghiệp vụ ban đầu.

-- SchemaTool thực thi toàn bộ tệp trong một giao dịch, kiểm tra số dòng và hoàn tác khi có lỗi.

SET LOCAL TIME ZONE 'UTC';

DO $$ DECLARE r record; n bigint; BEGIN FOR r IN SELECT tablename FROM pg_tables WHERE schemaname='public' LOOP EXECUTE format('SELECT count(*) FROM public.%I', r.tablename) INTO n; IF n <> 0 THEN RAISE EXCEPTION 'Initialization requires empty tables; % contains % rows. Use a reviewed data migration instead.', r.tablename,n; END IF; END LOOP; END $$;

-- Tạo các bảng còn thiếu trước; các ràng buộc tham chiếu đến bảng khác được bổ sung ở bên dưới.

