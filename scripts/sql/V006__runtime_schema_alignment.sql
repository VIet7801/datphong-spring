-- Bổ sung schema cho các trường/bảng đã có trong code Booking/Fake Bank.
-- Không đổi kiểu jsonb/daterange, không xóa bảng hoặc dữ liệu giao dịch hiện có.
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS host_note varchar(500);
ALTER TABLE bookings ADD COLUMN IF NOT EXISTS hold_expires_at timestamp(6);
ALTER TABLE room_allocations ADD COLUMN IF NOT EXISTS hold_expires_at timestamp(6);
ALTER TABLE payments ADD COLUMN IF NOT EXISTS refunded_amount numeric(12,2) NOT NULL DEFAULT 0;
ALTER TABLE payments ADD COLUMN IF NOT EXISTS payer_account varchar(40);
ALTER TABLE refund_requests ADD COLUMN IF NOT EXISTS kind varchar(30) NOT NULL DEFAULT 'CANCELLATION';
ALTER TABLE refund_requests ADD COLUMN IF NOT EXISTS attempts integer NOT NULL DEFAULT 0;
ALTER TABLE refund_requests ADD COLUMN IF NOT EXISTS next_retry_at timestamp(6);

CREATE TABLE IF NOT EXISTS fakebank_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_no varchar(40) NOT NULL UNIQUE,
    holder_name varchar(120) NOT NULL,
    balance numeric(16,2) NOT NULL,
    currency varchar(5) NOT NULL,
    version bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS fakebank_transactions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type varchar(10) NOT NULL,
    idempotency_key varchar(160) NOT NULL UNIQUE,
    account_no varchar(40) NOT NULL,
    amount numeric(16,2) NOT NULL,
    currency varchar(5) NOT NULL,
    status varchar(10) NOT NULL,
    reference varchar(60) NOT NULL UNIQUE,
    related_reference varchar(60),
    failure_code varchar(60),
    created_at timestamp(6) NOT NULL
);
CREATE TABLE IF NOT EXISTS fakebank_webhook_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id varchar(60) NOT NULL,
    event_type varchar(40) NOT NULL,
    reference varchar(60) NOT NULL,
    idempotency_key varchar(160) NOT NULL,
    amount numeric(16,2) NOT NULL,
    currency varchar(5) NOT NULL,
    failure_code varchar(60),
    status varchar(10) NOT NULL,
    attempts integer NOT NULL,
    available_at timestamp(6) NOT NULL,
    last_error varchar(300),
    created_at timestamp(6) NOT NULL
);
CREATE TABLE IF NOT EXISTS payment_webhook_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id varchar(60) NOT NULL UNIQUE,
    event_type varchar(40) NOT NULL,
    payment_id bigint,
    received_at timestamp(6) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_fakebank_webhook_due ON fakebank_webhook_events(status, available_at);
